#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn linux_wrapped_symbol_list_is_sane() {
        // the `-Wl,--wrap` flags, so pin its shape: 14 unique names that
        // all look like PipeWire API entry points.
        assert_eq!(WRAPPED_SYMBOLS.len(), 14);
        let mut sorted: Vec<&str> = WRAPPED_SYMBOLS.into();
        sorted.sort_unstable();
        sorted.dedup();
        assert_eq!(sorted.len(), WRAPPED_SYMBOLS.len());
        assert!(WRAPPED_SYMBOLS.iter().all(|name| {
            name.starts_with("pw_") && name.chars().all(|c| c.is_ascii_lowercase() || c == '_')
        }));
    }

    #[test]
    fn linux_real_pipewire_resolves_even_without_preload() {
        // Harness binaries may drop the unused libpipewire dependency at
        // link time; the dlopen fallback must still resolve the real
        // pw_init instead of panicking (or jumping to a null stub).
        unsafe {
            static CACHE: Resolved = Resolved::new();
            static NAME: &CStr = unsafe { CStr::from_bytes_with_nul_unchecked(b"pw_init\0") };
            assert_ne!(real(NAME, &CACHE), 0);
        }
    }
}
