//! Keep `pipewire-rs` usable in a process that also links the prebuilt
//! libwebrtc static library (ADR 0003 camera owner).
//!
//! libwebrtc bundles dlopen-lazy PipeWire stubs (`pw_init` and twelve
//! others) as *hidden local* symbols in this executable. The Rust static
//! linker therefore binds every `pipewire-sys` call to those stubs, whose
//! pointer table stays null until WebRTC's own screen-capture path
//! initializes it. The first camera start then jumps to address 0
//! (`pipewire::init` -> hidden `pw_init` stub -> null `pw_init_ptr`),
//! which is the SIGSEGV observed at camera publication start.
//!
//! `build.rs` passes `-Wl,--wrap=<symbol>` for each colliding symbol, so
//! every undefined reference -- ours and WebRTC's internal callers alike --
//! lands in the `__wrap_pw_*` functions below. Each wrapper resolves the
//! real symbol once from the process's global scope: the exe's hidden
//! definitions are absent from its dynamic symbol table, so
//! `dlsym(RTLD_DEFAULT, ...)` finds `libpipewire-0.3.so.0`, which is a
//! direct dependency. WebRTC's stubs keep working unchanged because the
//! wrapped calls now hit the same real functions their table would have
//! provided after its own lazy init.

use std::ffi::{c_char, c_int, c_void, CStr};
use std::sync::atomic::{AtomicUsize, Ordering};
/// Colliding PipeWire symbols WebRTC stubs inside this executable.
/// Generated by `build.rs` from the same list that drives the `-Wl,--wrap`
/// link flags, so the module and the link step cannot drift.
include!(concat!(env!("OUT_DIR"), "/link-wrapped-pipewire.rs"));

struct Resolved(AtomicUsize);

impl Resolved {
    const fn new() -> Self {
        Resolved(AtomicUsize::new(0))
    }
}

/// Resolve the real symbol once, caching the address. Prefers the process
/// scope (the main binary always preloads libpipewire as a dependency);
/// falls back to loading it, which keeps wrappers alive in harness
/// binaries whose link dropped the unused dependency. Panics rather than
/// jumping to null if libpipewire cannot be loaded at all.
unsafe fn real(name: &'static CStr, cache: &'static Resolved) -> usize {
    let cached = cache.0.load(Ordering::Acquire);
    if cached != 0 {
        return cached;
    }
    let mut address = libc::dlsym(libc::RTLD_DEFAULT, name.as_ptr()) as usize;
    if address == 0 {
        const LIBPIPEWIRE: &[u8] = b"libpipewire-0.3.so.0\0";
        let handle = libc::dlopen(
            LIBPIPEWIRE.as_ptr().cast::<c_char>(),
            libc::RTLD_LAZY | libc::RTLD_GLOBAL,
        );
        if !handle.is_null() {
            address = libc::dlsym(handle, name.as_ptr()) as usize;
        }
    }
    assert!(
        address != 0,
        "libpipewire symbol {} is unavailable; cannot route around the WebRTC stub",
        name.to_string_lossy()
    );
    cache.0.store(address, Ordering::Release);
    address
}

macro_rules! wrap {
    ($wrapped:ident, $name:literal, ($($arg:ident: $ty:ty),*) $(-> $ret:ty)?) => {
        #[no_mangle]
        unsafe extern "C" fn $wrapped($($arg: $ty),*) $(-> $ret)? {
            static CACHE: Resolved = Resolved::new();
            static NAME: &CStr = unsafe { CStr::from_bytes_with_nul_unchecked(concat!($name, "\0").as_bytes()) };
            let real_fn: unsafe extern "C" fn($($ty),*) $(-> $ret)? =
                std::mem::transmute(real(NAME, &CACHE));
            real_fn($($arg),*)
        }
    };
}

